/** Derives the `preset-air-lean` plugin list in air/bundles/air/cordis.patch.yml from the `preset-air` list. */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { applyPolicies } from './gen-compaction-policies.ts'

/**
 * Plugin row ids that `preset-air` carries and `preset-air-lean` omits: schedule tools, the delegation group
 * (subagent control and list, subagent, subagent fork, workflow engine, workflow tool), and the goal command and tool.
 */
export const REMOVED_ROW_IDS: readonly string[] = ['tool-schedule', 'command-goal', 'tool-goal', 'delegation']

/** Marker line that opens the generated plugin list of the lean preset. */
export const BEGIN_MARKER = '# BEGIN generated by air/scripts/gen-preset-air-lean.ts; edit preset-air and run pnpm -C air run gen:lean'
/** Marker line that closes the generated plugin list of the lean preset. */
export const END_MARKER = '# END generated'

const PLUGIN_INDENT = 10
const ENTRY_START = /^ {10}- id: (\S+)/u

function indentOf(line: string): number {
  return line.length - line.trimStart().length
}

/**
 * Extract the `preset-air` plugin entries as text, one string per top-level plugin row.
 * @param patch - contents of the bundle patch file.
 * @returns entries keyed by row id, in file order, each with its original lines.
 */
export function presetAirEntries(patch: string): { id: string; lines: string[] }[] {
  const lines = patch.split('\n')
  const rowAt = lines.findIndex(line => line === '    - id: preset-air')
  if (rowAt < 0) throw new Error('gen-preset-air-lean: no preset-air row')
  const pluginsAt = lines.findIndex((line, index) => index > rowAt && line === '        plugins:')
  if (pluginsAt < 0) throw new Error('gen-preset-air-lean: preset-air has no plugins list')
  const entries: { id: string; lines: string[] }[] = []
  for (let index = pluginsAt + 1; index < lines.length; index += 1) {
    const line = lines[index] ?? ''
    if (line.trim() !== '' && indentOf(line) < PLUGIN_INDENT) break
    const start = ENTRY_START.exec(line)
    if (start !== null) entries.push({ id: start[1] ?? '', lines: [line] })
    else if (entries.length > 0) entries[entries.length - 1]?.lines.push(line)
  }
  for (const entry of entries) while (entry.lines.at(-1)?.trim() === '') entry.lines.pop()
  return entries
}

/**
 * Return the patch file text with the lean preset's generated plugin list rewritten.
 * @param patch - contents of the bundle patch file.
 * @returns the patch text whose generated block lists every preset-air plugin row except REMOVED_ROW_IDS, with policy blocks applied.
 */
export function regenerate(patch: string): string {
  const entries = presetAirEntries(patch)
  const missing = REMOVED_ROW_IDS.filter(id => !entries.some(entry => entry.id === id))
  if (missing.length > 0) throw new Error(`gen-preset-air-lean: removed ids not in preset-air: ${missing.join(', ')}`)
  const kept = entries.filter(entry => !REMOVED_ROW_IDS.includes(entry.id)).flatMap(entry => entry.lines)
  const lines = patch.split('\n')
  const begin = lines.findIndex(line => line.trim() === BEGIN_MARKER)
  const end = lines.findIndex(line => line.trim() === END_MARKER)
  if (begin < 0 || end < begin) throw new Error('gen-preset-air-lean: generated block markers missing in the patch file')
  const pad = ' '.repeat(PLUGIN_INDENT)
  const joined = [...lines.slice(0, begin), `${pad}${BEGIN_MARKER}`, ...kept, `${pad}${END_MARKER}`, ...lines.slice(end + 1)].join('\n')
  // The copied rows carry the full preset's policy block; applyPolicies gives the lean block its own values.
  return applyPolicies(joined)
}

const patchFile = join(import.meta.dirname, '..', 'bundles', 'air', 'cordis.patch.yml')

function main(argv: readonly string[]): number {
  const current = readFileSync(patchFile, 'utf8')
  const next = regenerate(current)
  if (argv.includes('--check')) {
    if (next === current) return 0
    console.error('gen-preset-air-lean: preset-air-lean is stale; run `pnpm -C air run gen:lean`')
    return 1
  }
  if (next !== current) writeFileSync(patchFile, next)
  return 0
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) process.exitCode = main(process.argv.slice(2))
