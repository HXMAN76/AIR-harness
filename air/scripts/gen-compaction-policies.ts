/**
 * Writes the `modelPolicies` block of compaction-basic into both AIR presets of air/bundles/air/cordis.patch.yml and, with
 * lean values, into the `compaction-basic` row of air/bundles/air-headless/cordis.patch.yml.
 *
 * The single source is the table below: window class and preset to compaction targets, and local model id to window class.
 * The block sits between marker comments inside the `compaction-basic` row of `preset-air` (full values) and of
 * `preset-air-lean` (lean values). Order and composition: `gen-preset-air-lean.ts` copies the `preset-air` rows into the lean
 * preset and then calls `applyPolicies`, so the lean block always carries lean values and never the copied full values.
 * This script rewrites both blocks directly. Each generator is idempotent and either may run first or alone.
 *
 * Why a table: compaction-basic derives its threshold as `min(window x thresholdRatio, window - reservedOutput - headroomTokens)`.
 * The default headroom of 65,536 tokens makes that negative for 16K and 32K windows, so compaction never ran on local models.
 * Each entry fixes the threshold and derives `headroomTokens = window - RESERVED_OUTPUT_TOKENS - threshold`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

/** Output tokens one routed request reserves (the `maxTokens` of the local model rows). */
export const RESERVED_OUTPUT_TOKENS = 4096
/** A reply keeps its full reserve only when the threshold is below `window - FULL_REPLY_MARGIN` (reserve plus 4,096 of slack). */
export const FULL_REPLY_MARGIN = 8192

/** Preset the policy block belongs to. */
export type PolicyPreset = 'full' | 'lean'

/** Compaction targets for one window class and preset. */
export interface PolicyTarget {
  /** Request size in tokens at which compaction starts. */
  readonly thresholdTokens: number
  /** Verbatim tail kept after compaction; absent means the upstream ratio default. */
  readonly retainTokens?: number
  /** Output limit of the summary request. */
  readonly summaryMaxTokens: number
}

/**
 * Targets by window class and preset. 24,576 is derived, not measured: the threshold is the midpoint of the 16K and 32K
 * values, lowered where the midpoint reached `window - 8192` (full: midpoint 16,500 exceeds 16,384, so 16,000), and the
 * summary limit is the midpoint of the neighbours (1,536). The fixed prompt (about 5,700 lean, 9,500 full) plus the default
 * retained tail (0.16 x (24,576 - 4,096) = 3,276) plus the summary stays below the threshold: 5,700 + 3,276 + 1,536 = 10,512
 * under 14,500 (lean), 9,500 + 3,276 + 1,536 = 14,312 under 16,000 (full).
 */
export const WINDOW_TARGETS: Readonly<Record<number, Readonly<Record<PolicyPreset, PolicyTarget>>>> = {
  16384: {
    lean: { thresholdTokens: 9000, retainTokens: 800, summaryMaxTokens: 1024 },
    // Full preset on 16K: the 9,500-token fixed prompt leaves no room for a full reply; not recommended.
    full: { thresholdTokens: 11000, retainTokens: 600, summaryMaxTokens: 800 },
  },
  24576: {
    lean: { thresholdTokens: 14500, summaryMaxTokens: 1536 },
    full: { thresholdTokens: 16000, summaryMaxTokens: 1536 },
  },
  32768: {
    lean: { thresholdTokens: 20000, summaryMaxTokens: 2048 },
    full: { thresholdTokens: 22000, summaryMaxTokens: 2048 },
  },
}

/** Local Ollama model ids to their `num_ctx` window. Models absent here keep the upstream compaction defaults. */
export const MODEL_WINDOWS: Readonly<Record<string, number>> = {
  'qwen3-8b-16k': 16384,
  'qwen3-8b-32k': 32768,
  'qwen35-4b-32k': 32768,
  'qwen35-9b-24k': 24576,
  'qwen25-7b-32k': 32768,
  'gemma4-e4b-32k': 32768,
  'granite42-8b-16k': 16384,
  'granite42-3b-32k': 32768,
  'llama31-8b-16k': 16384,
}

/** Provider id of the local route. */
export const PROVIDER = 'ollama'

/** Marker line that opens a generated policy block. */
export const BEGIN_MARKER = '# BEGIN generated by air/scripts/gen-compaction-policies.ts; edit its table and run pnpm -C air run gen:policies'
/** Marker line that closes a generated policy block. */
export const END_MARKER = '# END generated policies'

/** One resolved `modelPolicies` entry as written to the preset. */
export interface ModelPolicy {
  readonly provider: string
  readonly model: string
  readonly headroomTokens: number
  readonly retainTokens?: number
  readonly maxTokens: number
}

/**
 * Resolve the policy entries of one preset from the table.
 * @param preset - which preset's values to use.
 * @returns one entry per model id, in table order, with `headroomTokens` derived from the threshold.
 */
export function policiesFor(preset: PolicyPreset): ModelPolicy[] {
  return Object.entries(MODEL_WINDOWS).map(([model, window]) => {
    const target = WINDOW_TARGETS[window]?.[preset]
    if (target === undefined) throw new Error(`gen-compaction-policies: no targets for window ${window} (${model})`)
    const base = { provider: PROVIDER, model, headroomTokens: window - RESERVED_OUTPUT_TOKENS - target.thresholdTokens }
    return target.retainTokens === undefined
      ? { ...base, maxTokens: target.summaryMaxTokens }
      : { ...base, retainTokens: target.retainTokens, maxTokens: target.summaryMaxTokens }
  })
}

/**
 * Render the YAML lines between the markers.
 * @param preset - which preset's values to use.
 * @param indent - indentation of the marker lines.
 * @returns the lines of the `modelPolicies` list, each prefixed by `indent`.
 */
export function renderBlock(preset: PolicyPreset, indent: string): string[] {
  const lines = [`${indent}modelPolicies:`]
  for (const policy of policiesFor(preset)) {
    lines.push(`${indent}  - provider: ${policy.provider}`, `${indent}    model: ${policy.model}`, `${indent}    headroomTokens: ${policy.headroomTokens}`)
    if (policy.retainTokens !== undefined) lines.push(`${indent}    retainTokens: ${policy.retainTokens}`)
    lines.push(`${indent}    maxTokens: ${policy.maxTokens}`)
  }
  return lines
}

const PRESET_ROW = /^ {4}- id: (preset-air-lean|preset-air)$/u

/**
 * Rewrite every policy block in the patch text.
 * @param patch - contents of the bundle patch file; each preset row holds exactly one marker pair.
 * @returns the patch text with the `preset-air` block holding full values and the `preset-air-lean` block lean values.
 */
export function applyPolicies(patch: string): string {
  const out: string[] = []
  let preset: PolicyPreset | undefined
  let skipping = false
  const seen: Record<PolicyPreset, number> = { full: 0, lean: 0 }
  for (const line of patch.split('\n')) {
    if (skipping) {
      if (line.trim() === END_MARKER) {
        skipping = false
        out.push(line)
      }
      continue
    }
    const row = PRESET_ROW.exec(line)
    if (row !== null) preset = row[1] === 'preset-air-lean' ? 'lean' : 'full'
    else if (/^ {4}- id:/u.test(line)) preset = undefined
    out.push(line)
    if (line.trim() !== BEGIN_MARKER) continue
    if (preset === undefined) throw new Error('gen-compaction-policies: policy markers outside a preset row')
    seen[preset] += 1
    out.push(...renderBlock(preset, line.slice(0, line.length - line.trimStart().length)))
    skipping = true
  }
  if (skipping) throw new Error('gen-compaction-policies: policy block has no end marker')
  if (seen.full !== 1 || seen.lean !== 1) throw new Error('gen-compaction-policies: each preset needs exactly one policy marker pair')
  return out.join('\n')
}

/**
 * Rewrite the single policy block of the headless bundle patch, which carries the lean tool set and so the lean values.
 * @param patch - contents of the headless bundle patch file; it holds exactly one marker pair.
 * @returns the patch text with the block between the markers holding the lean values.
 */
export function applyHeadlessPolicies(patch: string): string {
  const out: string[] = []
  let skipping = false
  let seen = 0
  for (const line of patch.split('\n')) {
    if (skipping) {
      if (line.trim() === END_MARKER) {
        skipping = false
        out.push(line)
      }
      continue
    }
    out.push(line)
    if (line.trim() !== BEGIN_MARKER) continue
    seen += 1
    out.push(...renderBlock('lean', line.slice(0, line.length - line.trimStart().length)))
    skipping = true
  }
  if (skipping) throw new Error('gen-compaction-policies: headless policy block has no end marker')
  if (seen !== 1) throw new Error('gen-compaction-policies: the headless bundle needs exactly one policy marker pair')
  return out.join('\n')
}

const bundles = join(import.meta.dirname, '..', 'bundles')
const targets: readonly { file: string; apply: (text: string) => string }[] = [
  { file: join(bundles, 'air', 'cordis.patch.yml'), apply: applyPolicies },
  { file: join(bundles, 'air-headless', 'cordis.patch.yml'), apply: applyHeadlessPolicies },
]

function main(argv: readonly string[]): number {
  let status = 0
  for (const { file, apply } of targets) {
    const current = readFileSync(file, 'utf8')
    const next = apply(current)
    if (next === current) continue
    if (argv.includes('--check')) {
      console.error(`gen-compaction-policies: policy blocks in ${file} are stale; run \`pnpm -C air run gen:policies\``)
      status = 1
    } else writeFileSync(file, next)
  }
  return status
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) process.exitCode = main(process.argv.slice(2))
